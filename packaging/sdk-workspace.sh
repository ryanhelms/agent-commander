#!/bin/sh
# Write dist/go.work, which points the root Go module at local agent-acp and
# agent-acp-transport checkouts, and print its path.
#
# go.mod's replace directives use ../agent-acp, which only resolves from a
# primary checkout that sits beside the SDKs. This script finds them from any
# checkout or linked worktree, in this order:
#   1. AGENT_ACP_DIR and AGENT_ACP_TRANSPORT_DIR
#   2. beside this checkout
#   3. beside the primary checkout of this repository (for linked worktrees)
# Use the result with GOWORK, for example:
#   export GOWORK="$(sh packaging/sdk-workspace.sh)"
set -eu

top=$(git rev-parse --show-toplevel)
common=$(git rev-parse --path-format=absolute --git-common-dir)
primary=$(dirname "$common")

find_checkout() {
	for candidate in "$2" "$top/../$1" "$primary/../$1"; do
		if [ -n "$candidate" ] && [ -d "$candidate" ]; then
			(cd "$candidate" && pwd -P)
			return 0
		fi
	done
	return 1
}

if ! acp=$(find_checkout agent-acp "${AGENT_ACP_DIR:-}") ||
	! transport=$(find_checkout agent-acp-transport "${AGENT_ACP_TRANSPORT_DIR:-}"); then
	echo "agent-commander: cannot find the agent-acp and agent-acp-transport checkouts." >&2
	echo "Clone them beside agent-commander, or set AGENT_ACP_DIR and AGENT_ACP_TRANSPORT_DIR." >&2
	exit 1
fi

version=$(sed -n 's/^go \([0-9.]*\).*/\1/p' "$top/go.mod")
mkdir -p "$top/dist"
work="$top/dist/go.work"
cat >"$work" <<EOF
// Generated by packaging/sdk-workspace.sh. Do not edit.
go $version

use ..

replace agent-acp.local/sdks/go => $acp/sdks/go

replace agent-acp.local/transport => $transport
EOF
echo "$work"
